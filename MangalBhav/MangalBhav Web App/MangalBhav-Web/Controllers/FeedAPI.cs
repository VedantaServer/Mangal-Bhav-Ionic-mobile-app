		/// <summary>
		/// Creates a new instance of the Feed class and populates it with data from the specified SqlDataReader.
		/// </summary>
		public  Feed MakeFeed(SqlDataReader dataReader)
		{
			Feed feed = new Feed();
			feed.FeedID = DataAccess.GetInt32(dataReader, "FeedID", 0);
			feed.TenantID = DataAccess.GetInt32(dataReader, "TenantID", 0);
			feed.UserID = DataAccess.GetInt32(dataReader, "UserID", 0);
			feed.Title = DataAccess.GetString(dataReader, "Title", String.Empty);
			feed.Description = DataAccess.GetString(dataReader, "Description", String.Empty);
			feed.MediaType = DataAccess.GetString(dataReader, "MediaType", String.Empty);
			feed.PostType = DataAccess.GetString(dataReader, "PostType", String.Empty);
			feed.MediaURL = DataAccess.GetString(dataReader, "MediaURL", String.Empty);
			feed.ThumbnailURL = DataAccess.GetString(dataReader, "ThumbnailURL", String.Empty);
			feed.Duration = DataAccess.GetInt32(dataReader, "Duration", 0);
			feed.DisplayOrder = DataAccess.GetInt32(dataReader, "DisplayOrder", 0);
			feed.PublishDate = DataAccess.GetDateTime(dataReader, "PublishDate", DateTime.MinValue);
			feed.IsActive = DataAccess.GetBoolean(dataReader, "IsActive", false);
			feed.IsDeleted = DataAccess.GetBoolean(dataReader, "IsDeleted", false);
			feed.IsAdminPost = DataAccess.GetBoolean(dataReader, "IsAdminPost", false);
			feed.DateAdded = DataAccess.GetDateTime(dataReader, "DateAdded", DateTime.MinValue);
			feed.DateModified = DataAccess.GetDateTime(dataReader, "DateModified", DateTime.MinValue);
			feed.UpdatedByUser = DataAccess.GetString(dataReader, "UpdatedByUser", String.Empty);
			feed.SourceTable = DataAccess.GetString(dataReader, "SourceTable", String.Empty);
			feed.SourceID = DataAccess.GetInt32(dataReader, "SourceID", 0);
			feed.UserName = DataAccess.GetString(dataReader, "UserName", String.Empty);
			feed.UserPhoto = DataAccess.GetString(dataReader, "UserPhoto", String.Empty);
			feed.FeedCategory = DataAccess.GetString(dataReader, "FeedCategory", String.Empty);
			feed.Location = DataAccess.GetString(dataReader, "Location", String.Empty);
			feed.Amount = DataAccess.GetDecimal(dataReader, "Amount", Decimal.Zero);
			feed.IsAutoGenerated = DataAccess.GetBoolean(dataReader, "IsAutoGenerated", false);

			return feed;
		}

