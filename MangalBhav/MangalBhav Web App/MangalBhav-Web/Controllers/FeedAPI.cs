		/// <summary>
		/// Selects a single record from the Feed table.
		/// </summary>
	[HttpPost]
        [EnableCors("AllowAll")]
        [Route("FeedSelect")]
		public IActionResult FeedSelect(int feedID,int tenantID)
		{
			return ApiHandler.Handle(() =>
	{
			SqlParameter[] parameters = new SqlParameter[]
			{
				new SqlParameter("@FeedID", feedID)
,				new SqlParameter("@TenantID", tenantID)
			};

			using (SqlDataReader dataReader = DataAccess.ExecuteReader(CommandType.StoredProcedure, "FeedSelect", parameters))
			{
				List<Feed> FeedList = new List<Feed>();
				while (dataReader.Read())
				{
					Feed Feed = MakeFeed(dataReader);
					FeedList.Add(Feed);
				}

				return  Ok(new {FeedList});
			}
			}, this);
		}

